// Regenerates src/data/charComponents.ts from Make Me a Hanzi's dictionary.txt.
// Usage: node scripts/gen-char-data.mjs path/to/dictionary.txt
// Source: https://github.com/skishore/makemeahanzi (dictionary.txt, LGPL-3.0-or-later).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'

const [dictionaryPath] = process.argv.slice(2)
if (!dictionaryPath) throw new Error('Usage: node scripts/gen-char-data.mjs path/to/dictionary.txt')

const HAN = /\p{Script=Han}/u
// Include all course characters, not only those already present in radicalMap.ts.
const radicalMap = readFileSync(new URL('../src/data/radicalMap.ts', import.meta.url), 'utf8')
const groups = radicalMap.slice(radicalMap.indexOf('GROUPS'), radicalMap.indexOf('\n}\n'))
// Characters used by the beginner sessions on how characters are built.
const INTRO = '一二三上下本末刃人口日月山水火木目手女子大小田门马鱼雨车耳心休明林森男好妈吗骂们你他问河海说话打'
// Characters from the HSK 2.0 curriculum levels 1–6.
const curriculumDir = new URL('../src/data/curriculum/', import.meta.url)
const curriculum = readdirSync(curriculumDir).filter((name) => /^level[1-6]\.ts$/.test(name)).map((name) => readFileSync(new URL(name, curriculumDir), 'utf8')).join('')
const wanted = new Set([...groups + INTRO + curriculum].filter((ch) => HAN.test(ch)))

const rows = []
for (const line of readFileSync(dictionaryPath, 'utf8').split('\n')) {
  if (!line) continue
  const entry = JSON.parse(line)
  if (!wanted.has(entry.character)) continue
  const e = entry.etymology ?? {}
  const type = { pictographic: 'p', ideographic: 'i', pictophonetic: 's' }[e.type] ?? '-'
  // Component path of each stroke in the decomposition tree, e.g. 妈 → "0,0,0,1,1,1", 学 → "00,00,00,01,01,1,1,1"; "-" unknown.
  const matches = (entry.matches ?? []).map((m) => (m && m.length ? m.join('') : '-')).join(',')
  rows.push([entry.character, type, entry.decomposition, e.semantic ?? '', e.phonetic ?? '', matches, entry.radical ?? ''].join('|'))
  wanted.delete(entry.character)
}
rows.sort()

writeFileSync(new URL('../src/data/charComponents.ts', import.meta.url), `/** How each course character is built. Generated by scripts/gen-char-data.mjs from
 * Make Me a Hanzi dictionary.txt (github.com/skishore/makemeahanzi, LGPL-3.0-or-later),
 * itself derived from Unihan and CJKlib. Keep this static for offline lookup.
 * Row: char | type (p tượng hình, i hội ý/chỉ sự, s hình thanh, - chưa rõ) | IDS decomposition | semantic | phonetic
 *      | component path of each stroke in the decomposition tree ("-" unknown) | dictionary radical */
const ROWS = \`${rows.join('\n')}\`

export type CharType = 'pictographic' | 'ideographic' | 'pictophonetic'

export interface CharComponents {
  /** Ideographic description sequence, e.g. "⿰女马". "？" marks an unknown part. */
  decomposition: string
  type?: CharType
  /** Component carrying the meaning (hình thanh). */
  semantic?: string
  /** Component hinting at the sound (hình thanh). */
  phonetic?: string
  /** For each stroke, its path in the decomposition tree ([] when unknown), e.g. 学 stroke 0 → [0, 0] = ⺍. */
  strokes: number[][]
  /** Dictionary radical as Make Me a Hanzi lists it (used where radicalMap.ts has no entry). */
  radical?: string
}

const TYPES: Record<string, CharType> = { p: 'pictographic', i: 'ideographic', s: 'pictophonetic' }

export const CHAR_COMPONENTS = new Map<string, CharComponents>(ROWS.split('\\n').map((row) => {
  const [char, type, decomposition, semantic, phonetic, matches = '', radical = ''] = row.split('|')
  return [char, { decomposition, type: TYPES[type], semantic: semantic || undefined, phonetic: phonetic || undefined, radical: radical || undefined, strokes: matches ? matches.split(',').map((m) => (m === '-' ? [] : [...m].map(Number))) : [] }]
}))

const isPart = (ch: string) => /\\p{Script=Han}/u.test(ch) || /[\\u2E80-\\u2FDF]/u.test(ch)

/** Direct parts of a character, skipping layout operators and unknown pieces. */
export function componentsOf(char: string): string[] {
  return [...(CHAR_COMPONENTS.get(char)?.decomposition ?? '')].filter(isPart)
}

type Tree = string | Tree[]
const ARITY: Record<string, number> = { '⿲': 3, '⿳': 3 }

/** Parse an IDS like "⿱⿱⺍冖子" into nested operands: [['⺍', '冖'], '子']. */
function parseIds(ids: string): Tree {
  const chars = [...ids]
  let i = 0
  const read = (): Tree => {
    const ch = chars[i++] ?? '？'
    if (!/[\\u2FF0-\\u2FFB]/u.test(ch)) return ch
    return Array.from({ length: ARITY[ch] ?? 2 }, read)
  }
  return read()
}

/**
 * For each stroke, the parts it belongs to from the outside in, e.g. 您 stroke 0 → ['你', '亻'].
 * A part's own parts are followed when its stroke data lines up (same stroke count).
 */
export function strokeParts(char: string): string[][] {
  const data = CHAR_COMPONENTS.get(char)
  if (!data) return []
  const tree = parseIds(data.decomposition)
  const leafOf = (path: number[]) => path.reduce<Tree | undefined>((node, k) => (Array.isArray(node) ? node[k] : undefined), tree)
  const seen = new Map<string, number>()
  return data.strokes.map((path) => {
    const leaf = path.length ? leafOf(path) : undefined
    if (typeof leaf !== 'string' || leaf === '？') return []
    const key = path.join('')
    const n = seen.get(key) ?? 0
    seen.set(key, n + 1)
    const inner = CHAR_COMPONENTS.get(leaf)
    const count = data.strokes.filter((p) => p.join('') === key).length
    return inner && leaf !== char && inner.strokes.length === count ? [leaf, ...(strokeParts(leaf)[n] ?? [])] : [leaf]
  })
}
`)
console.log(`${rows.length} rows written${wanted.size ? `; missing: ${[...wanted].join('')}` : ''}`)
