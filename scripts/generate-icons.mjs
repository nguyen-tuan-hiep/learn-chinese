#!/usr/bin/env node
/**
 * Draws the app icons from the bánh bao mascot (same artwork as src/components/layout/BrandMark.tsx):
 * public/app-icon.svg (favicon, splash source), apple-touch-icon.png, icon-192.png, icon-512.png, icon-maskable-512.png.
 * Run: node scripts/generate-icons.mjs   (needs rsvg-convert: brew install librsvg)
 * Then regenerate the iOS launch images: node scripts/generate-splash.mjs
 */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const pub = (file) => join(root, 'public', file)

/** The mascot in its 44×44 box, centred on (22, 23). */
const BAO = `
  <circle cx="29" cy="30" r="9" fill="#f6c9a8" opacity="0.9" filter="url(#glow)"/>
  <circle cx="13" cy="20" r="6" fill="#ffffff" opacity="0.6" filter="url(#glow)"/>
  <path d="M4 30c0-12 8.5-22 18-22s18 10 18 22c0 4.5-4 7.5-18 7.5S4 34.5 4 30z" fill="url(#body)" stroke="url(#rim)" stroke-width="1.4"/>
  <ellipse cx="13" cy="17.5" rx="4.6" ry="2" fill="#fff" opacity="0.75" transform="rotate(-32 13 17.5)"/>
  <g fill="none" stroke="#15120f" stroke-width="2" stroke-linecap="round">
    <path d="M16 11.5c2 3 4 4 6 4s4-1 6-4"/><path d="M22 8.5v7"/><path d="M19.5 28.5q2.5 2.6 5 0" stroke-width="1.8"/>
  </g>
  <circle cx="15.5" cy="25" r="2" fill="#15120f"/><circle cx="28.5" cy="25" r="2" fill="#15120f"/>
  <ellipse cx="11" cy="29.2" rx="2.6" ry="1.5" fill="#f08fae" opacity="0.8"/><ellipse cx="33" cy="29.2" rx="2.6" ry="1.5" fill="#f08fae" opacity="0.8"/>`

/** Full-bleed square icon; `scale` sets the mascot size (smaller for the maskable safe zone). */
const icon = (scale) => `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
<!-- App icon: the white bánh bao mascot in frosted glass on a one-hue peach background. Generated by scripts/generate-icons.mjs. -->
<defs>
  <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#fff3ea"/><stop offset="1" stop-color="#f9d6bd"/></linearGradient>
  <linearGradient id="body" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#ffffff" stop-opacity="0.95"/><stop offset="1" stop-color="#e8dfd2" stop-opacity="0.8"/></linearGradient>
  <linearGradient id="rim" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#fff" stop-opacity="0.95"/><stop offset="1" stop-color="#fff" stop-opacity="0.15"/></linearGradient>
  <filter id="glow" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="3.2"/></filter>
</defs>
<rect width="1024" height="1024" fill="url(#bg)"/>
<g transform="translate(${512 - 22 * scale} ${512 - 23 * scale}) scale(${scale})">${BAO}
</g>
</svg>
`

writeFileSync(pub('app-icon.svg'), icon(17))
const work = mkdtempSync(join(tmpdir(), 'icons-'))
const maskable = join(work, 'maskable.svg')
writeFileSync(maskable, icon(13))
const render = (src, size, file) => execFileSync('rsvg-convert', ['-w', String(size), '-h', String(size), src, '-o', pub(file)])
render(pub('app-icon.svg'), 180, 'apple-touch-icon.png')
render(pub('app-icon.svg'), 192, 'icon-192.png')
render(pub('app-icon.svg'), 512, 'icon-512.png')
render(maskable, 512, 'icon-maskable-512.png')
console.log('Icons written to public/')
